async function main() {
  let user = await prisma.user.findFirst({ where: { email: 'collector@banknotes.app' } });
  if (!user) {
    user = await prisma.user.create({
      data: {
        email: 'collector@banknotes.app',
        name: 'Primary Collector',
        role: 'COLLECTOR',
      }
    });
  }

  for (const n of SEED_NOTES) {
    await prisma.banknote.upsert({
      where: { id: n.id },
      update: {},
      create: {
        ...n,
        userId: user.id,
        syncStatus: 'SYNCED',
        syncedAt: new Date(),
      }
    });
  }

  const count = await prisma.banknote.count();
  console.log(`✅ Successfully seeded Neon database 'banknotes'! Total records: ${count}`);
  await prisma.$disconnect();
}

main().catch(err => {
  console.error('Seed error:', err);
  process.exit(1);
});
